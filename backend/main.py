@app.post("/api/generate-sql")
def generate_sql_endpoint(req: GenerateSQLRequest):
    """
    Translates a natural language question into safe PostgreSQL.
    Recalls Hindsight memory context, applies SQLGlot AST validation,
    and runs self-healing retry loop if necessary.
    """
    try:
        q = req.question or req.query or ""
        result = generate_and_validate_sql(
            question=q,
            use_memory=req.use_memory
        )
        return result
    except Exception as e:
        logger.error(f"Generate SQL error: {e}")
        raise HTTPException(status_code=500, detail=str(e))


@app.post("/api/execute-sql")
@app.post("/api/v1/query/execute")
def execute_sql_endpoint(req: ExecuteSQLRequest):
    """
    Safely executes a read-only SQL query against the database.
    Enforces AST validation and read-only session locks.
    """
    try:
        # Validate AST safety
        validate_sql_with_sqlglot(req.sql)
        # Execute query
        result = execute_readonly_sql(req.sql)
        try:
            from analytics import log_query_execution
            log_query_execution(
                natural_language_query=req.sql,
                generated_sql=req.sql,
                execution_status="SUCCESS",
                execution_time_ms=result.get("execution_time_ms", 0.0),
                rows_returned=result.get("row_count", 0),
                used_hindsight_memory=False
            )
        except Exception:
            pass
        return result
    except ValueError as ve:
        try:
            from analytics import log_query_execution
            log_query_execution(
                natural_language_query=req.sql,
                generated_sql=req.sql,
                execution_status="VALIDATION_ERROR",
                execution_time_ms=0.0,
                rows_returned=0,
                error_message=str(ve),
                used_hindsight_memory=False
            )
        except Exception:
            pass
        raise HTTPException(status_code=400, detail=f"Safety or syntax error: {ve}")
    except Exception as e:
        try:
            from analytics import log_query_execution
            log_query_execution(
                natural_language_query=req.sql,
                generated_sql=req.sql,
                execution_status="FAILED",
                execution_time_ms=0.0,
                rows_returned=0,
                error_message=str(e),
                used_hindsight_memory=False
            )
        except Exception:
            pass
        raise HTTPException(status_code=500, detail=f"Database execution error: {e}")


@app.post("/api/query")
@app.post("/api/v1/query")
@app.post("/api/v1/query/generate")
def full_query_endpoint(req: QueryRequest):
    """
    End-to-end endpoint: generates SQL using Hindsight memory, validates it,
    and executes it against the database in a single call.
    Returns: { sql, sqlglot_valid, results, memory_inspector, ... }
    """
    try:
        q = req.question or req.query or ""
        if not q.strip():
            raise HTTPException(status_code=400, detail="Missing question or query field.")

        gen_result = generate_and_validate_sql(
            question=q,
            use_memory=req.use_memory
        )
        return gen_result
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


