@app.post("/api/feedback")
@app.post("/api/correct")
@app.post("/memory/retain")
@app.post("/api/memory/retain")
@app.post("/api/v1/memory/retain")
def human_correction_endpoint(req: HumanCorrectionRequest):
    """
    Analyst correction endpoint: stores company business rules and
    SQL correction experience into Hindsight Cloud semantic memory.
    """
    try:
        q = req.question or req.title or "General NovaMart Rule"
        rule = req.business_rule or req.ruleText or req.description or ""
        wrong = req.wrong_sql or req.description or "None"
        corrected = req.corrected_sql or ""

        result = retain_human_correction(
            question=q,
            wrong_sql=wrong,
            corrected_sql=corrected,
            business_rule=rule
        )

        # Safely log to PostgreSQL learning_events (Phase 2)
        try:
            from analytics import log_learning_event
            log_learning_event(
                correction_text=rule or f"{q}: {corrected}",
                category=req.categoryTag or req.type or "business_rule",
                verification_status="verified"
            )
        except Exception as e_ev:
            logger.warning(f"Failed to record learning event: {e_ev}")

        return {
            "status": "success",
            "message": "Human correction retained in Hindsight Memory.",
            "details": result,
            "id": f"mem-{int(time.time())}",
            "type": req.type or "human_correction",
            "title": req.title or q,
            "description": req.description or wrong,
            "ruleText": rule,
            "createdAt": datetime.utcnow().isoformat(),
            "confidenceScore": 0.99,
            "timesApplied": 1,
            "author": req.author or "Current User / GP",
            "verified": True,
            "categoryTag": req.categoryTag or "Business Rule",
        }
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to retain correction: {e}")


